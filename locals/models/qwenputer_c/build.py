"""Build the toolbox's C for Qwenputer's computer: RV32IM + Zba, linked at fixed addresses (link.ld), written as
qwenputer_tools_c.s next to qwenputer.py (the code as words, the read-only data as bytes, with the sources' digest),
which toolbox() links after calc's firmware and qwenputer_tools.s.

    python locals/models/qwenputer_c/build.py [--elf COPY]

It needs a clang that targets RISC-V: zig's (pip install ziglang, or ZIG=/path/to/zig) or LLVM's (CC=clang)."""

import hashlib
import os
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE.parent / "qwenputer_tools_c.s"
TEXT, RODATA, RAM = 0x48000, 0x22000, (0x800, 0x1A00)
SOURCES = sorted(p for p in HERE.glob("*.c") if p.name != "host.c")
FLAGS = ["-O2", "-fomit-frame-pointer", "-ffreestanding", "-nostdlib", "-fno-pic", "-mno-relax", "-fno-stack-protector", "-fno-builtin",
         "-Wall", "-Wextra", "-Wno-unused-parameter", "-Werror"]


def digest() -> str:
    """The sources' digest (every .c, .h and link.ld here but host.c)."""
    h = hashlib.sha256()
    for p in sorted(list(HERE.glob("*.c")) + list(HERE.glob("*.h")) + [HERE / "link.ld"]):
        if p.name != "host.c":
            h.update(p.name.encode() + b"\0" + p.read_bytes() + b"\0")
    return h.hexdigest()


def compiler() -> list:
    if os.environ.get("CC"):
        return [os.environ["CC"], "--target=riscv32-unknown-elf", "-march=rv32im_zba", "-mabi=ilp32", "-fuse-ld=lld"]
    zig = os.environ.get("ZIG") or shutil.which("zig")
    if not zig:
        try:
            import ziglang  # noqa: F401

            zig = str(Path(ziglang.__file__).parent / "zig")
        except ImportError:
            sys.exit("no RISC-V compiler: pip install ziglang, or set ZIG or CC (an LLVM clang)")
    return [zig, "cc", "-target", "riscv32-freestanding-none", "-mcpu=generic_rv32+m+zba"]


def sections(elf: bytes) -> dict:
    """name -> (address, bytes or None for NOBITS) of the sections that take memory"""
    shoff, = struct.unpack_from("<I", elf, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", elf, 0x2E)
    heads = [struct.unpack_from("<10I", elf, shoff + i * shentsize) for i in range(shnum)]
    names = heads[shstrndx][4]
    out = {}
    for name, typ, flags, addr, off, size, *_ in heads:
        n = elf[names + name:elf.index(b"\0", names + name)].decode()
        if n and size and typ in (1, 8) and flags & 2:  # (SHF_ALLOC)
            out[n] = (addr, None if typ == 8 else elf[off:off + size])
    return out


def main():
    cc = compiler()
    with tempfile.TemporaryDirectory() as d:
        elf_path = Path(d) / "tools.elf"
        subprocess.run(cc + FLAGS + ["-T", str(HERE / "link.ld"), "-Wl,-e,c_main", "-o", str(elf_path)]
                       + [str(p) for p in SOURCES], check=True)
        version = subprocess.run(cc[:2] + ["--version"] if cc[1] != "cc" else [cc[0], "version"],
                                 capture_output=True, text=True).stdout.split("\n")[0].strip()
        s = sections(elf_path.read_bytes())
        if len(sys.argv) > 2 and sys.argv[1] == "--elf":  # (a copy, with its symbols, to profile a run)
            shutil.copy(elf_path, sys.argv[2])
    text, rodata = s.pop(".text"), s.pop(".rodata", (RODATA, b""))
    bss = s.pop(".bss", (RAM[0], None))
    assert text[0] == TEXT and rodata[0] == RODATA, (hex(text[0]), hex(rodata[0]))
    assert not s, f"sections the computer has no place for: {sorted(s)}"  # (.data: no initialized data)
    assert RAM[0] <= bss[0] < RAM[1]
    code = text[1]
    assert len(code) % 4 == 0
    words = struct.unpack(f"<{len(code) // 4}I", code)
    assert all(w & 3 == 3 for w in words), "a compressed instruction"
    lines = [f"; Generated by qwenputer_c/build.py from qwenputer_c/ (sources sha256 {digest()}): do not edit.",
             f"; The toolbox's tools in C, compiled for Qwenputer's computer (RV32IM + Zba; zig {version}, -O2) and linked",
             f"; at fixed addresses: code from {TEXT:#x} (c_main first), read-only data from {RODATA:#x}. {len(code)} bytes",
             f"; of code, {len(rodata[1])} of read-only data.",
             ".text"]
    lines += [".word " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) for i in range(0, len(words), 8)]
    lines.append(".rodata")
    ro = rodata[1]
    lines += [".byte " + ", ".join(str(b) for b in ro[i:i + 32]) for i in range(0, len(ro), 32)]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT.name}: {len(code)} bytes of code, {len(ro)} of read-only data")


if __name__ == "__main__":
    main()
